      if (flag)
        this.errRecommend.SetError((Control) this.chkLargeExport, str);
    }
    if (this.txtSumFields.Text.Trim() != "")
    {
      string str = "Large Data Export reports does not support 'Summary Fields' \r\n";
      text += str;
      this.errRecommend.SetError((Control) this.txtSumFields, str);
    }
    if (Verbose && text != "")
    {
      if (flag)
      {
        int num1 = (int) MessageBox.Show(text, "Large Data Export limitations", MessageBoxButtons.OK, MessageBoxIcon.Asterisk);
      }
      else
      {
        int num2 = (int) MessageBox.Show(text, "Large Data Export limitations", MessageBoxButtons.OK, MessageBoxIcon.Hand);
      }
    }
    return flag;
  }

