  private string GenDataset()
  {
    this._report.Save();
    Type reportType = typeof (AdHocReportDisplay);
    string str1 = "";
    BaseReportControl[] getReportControls = this._report.getReportControls;
    Guid guid = this._report.GUID;
    frmAdHocReportLauncher hocReportLauncher = new frmAdHocReportLauncher(reportType, "Gathering Data for Designer", getReportControls, guid);
    hocReportLauncher.ShowInTaskbar = false;
    hocReportLauncher.AutoScroll = true;
    if (hocReportLauncher.ShowDialog() == DialogResult.Cancel)
      return (string) null;
    SqlCommand sqlCommand = hocReportLauncher.SQLCommand;
    this._AutoGeneratedLayout = hocReportLauncher.Layout;
    string str2 = sqlCommand.CommandText;
    if (sqlCommand.CommandType == CommandType.StoredProcedure)
    {
      foreach (SqlParameter parameter in (DbParameterCollection) sqlCommand.Parameters)
      {
        if (parameter.Value != null)
          str1 = $"{str1}{parameter.ParameterName}={this.FormatSqlParameter(parameter.Value.ToString(), parameter.DbType.ToString())}, ";
      }
      hocReportLauncher.Dispose();
      if (str1.Length > 2)
        str1 = str1.Substring(0, str1.Length - 2);
      return $"{str2} {str1}";
    }
    foreach (SqlParameter parameter in (DbParameterCollection) sqlCommand.Parameters)
    {
      if (parameter.Value != null)
        str2 = str2.Replace(parameter.ParameterName, this.FormatSqlParameter(parameter.Value.ToString(), parameter.DbType.ToString()));
    }
    return str2;
  }

