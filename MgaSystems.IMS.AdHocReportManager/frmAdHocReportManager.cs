      this.errError.SetError((Control) this.chkScreen, str);
      this.errError.SetError((Control) this.chkLargeExport, str);
      flag = false;
    }
    if (!this.chkThreaded.Checked)
    {
      string str = "Please check 'Is Threaded' on the 'Report Properties' tab. \r\n";
      text += "It is highly recommended to run Large Data reports in threaded mode. Please check 'Is Threaded' on the 'Report Properties' tab. \r\n";
