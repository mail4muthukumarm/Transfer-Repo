  private void PopulateParamsDropDown()
  {
    try
    {
      SqlCommand cmd = new SqlCommand(this._report.SQL.Trim(), new SqlConnection(DefaultDatabase.ConnectionString));
      if (cmd.CommandText.Substring(0, 6).ToUpper() == "SELECT")
        cmd.CommandType = CommandType.Text;
      else
        cmd.CommandType = CommandType.StoredProcedure;
      if (cmd.Connection.State != ConnectionState.Open)
        cmd.Connection.Open();
      this.DeriveParameters(cmd);
      cmd.Connection.Close();
      this.ddbParams.DropDownItems.Clear();
      this.ddbParamsSubTitle.DropDownItems.Clear();
      this._ReturnParameters.Clear();
      foreach (SqlParameter parameter in (DbParameterCollection) cmd.Parameters)
      {
        this.ddbParams.DropDownItems.Add(parameter.ParameterName);
        this.ddbParamsSubTitle.DropDownItems.Add(parameter.ParameterName);
        this._ReturnParameters.Add(parameter.ParameterName);
      }
    }
    catch (Exception ex)
    {
    }
  }

  private SqlParameterCollection DeriveParameters(SqlCommand cmd)
  {
    if (cmd.CommandType == CommandType.StoredProcedure)
    {
      SqlCommandBuilder.DeriveParameters(cmd);
      cmd.Parameters.RemoveAt(cmd.Parameters.IndexOf("@RETURN_VALUE"));
    }
    else
    {
      cmd.Parameters.Clear();
      int startIndex1 = 0;
      string commandText = cmd.CommandText;
      char[] anyOf = new char[4]{ ' ', '=', ',', ')' };
      int startIndex2;
      for (; commandText.IndexOf("@", startIndex1) > 0; startIndex1 = startIndex2 + 1)
      {
        startIndex2 = commandText.IndexOf("@", startIndex1);
        int num = commandText.IndexOfAny(anyOf, startIndex2);
        if (num < 1)
          num = commandText.Length;
        string str = commandText.Substring(startIndex2, num - startIndex2);
        SqlParameter sqlParameter = new SqlParameter();
        sqlParameter.ParameterName = str;
        if (!cmd.Parameters.Contains(str) && str != "@RETURN_VALUE")
          cmd.Parameters.Add(sqlParameter);
      }
    }
    return cmd.Parameters;
  }

  private XmlDocument AddDataSourceToLayout(string _layout, string strDataSetNode)
  {
    if (strDataSetNode == null)
      return (XmlDocument) null;
    XmlDocument layout = new XmlDocument();
    layout.LoadXml(_layout);
    XmlNode lastChild = layout.DocumentElement.LastChild;
    XmlNode node = layout.CreateNode(XmlNodeType.Element, "DataSources", (string) null);
    XmlElement element = layout.CreateElement("SqlDbDataSource");
    element.SetAttribute("Connect", DefaultDatabase.ConnectionString);
    element.SetAttribute("SQL", strDataSetNode);
    node.AppendChild((XmlNode) element);
    layout.DocumentElement.InsertAfter(node, lastChild);
    return layout;
  }

